"""Extract the pinned MIT Manim brace outline into affine-in-length Go data.

Development code generation, never a runtime parser or renderer. Run with the
pinned Manim environment and pass the destination Go file explicitly.
"""
import ast
import hashlib
from pathlib import Path
import subprocess
import sys

import svgelements as se

root = Path(__file__).resolve().parents[2]
source = root.parent / "manim"
commit = "16ea443e2a5f1d79db0a721161411ce916d6e733"
assert subprocess.check_output(["git", "-C", str(source), "rev-parse", "HEAD"], text=True).strip() == commit
tree = ast.parse((source / "manim/mobject/svg/brace.py").read_text())
cls = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "Brace")
fn = next(n for n in cls.body if isinstance(n, ast.FunctionDef) and n.name == "__init__")
template = next(ast.literal_eval(n.value) for n in fn.body if isinstance(n, ast.Assign)
                and any(isinstance(t, ast.Name) and t.id == "path_string_template" for t in n.targets))


def controls(length):
    output = []
    for segment in se.Path(template.format(length, -length)):
        if isinstance(segment, se.CubicBezier):
            output.append([segment.start, segment.control1, segment.control2, segment.end])
        elif isinstance(segment, (se.Line, se.Close)):
            a, b = segment.start, segment.end
            if isinstance(segment, se.Close) and abs(a-b) <= .0001:
                continue
            output.append([a, se.Point((2*a.x+b.x)/3, (2*a.y+b.y)/3),
                           se.Point((a.x+2*b.x)/3, (a.y+2*b.y)/3), b])
    return output


a, b = controls(0), controls(1)
assert len(a) == len(b) == 25
out = Path(sys.argv[1])
out.parent.mkdir(parents=True, exist_ok=True)
with out.open("x") as stream:
    stream.write("// Code generated by tests/reference/brace_template.py; DO NOT EDIT.\n")
    stream.write("// Manim CE 0.22.1 brace.py outline (MIT); see LICENSES/manim-LICENSE.community.txt.\n")
    stream.write("// Source commit: " + commit + "\n")
    stream.write("// Generator SHA256: " + hashlib.sha256(Path(__file__).read_bytes()).hexdigest() + "\n")
    stream.write("package gomath\n\nvar braceTemplate = [25][4][3]float64{\n")
    for c0, c1 in zip(a, b):
        values = []
        for p, q in zip(c0, c1):
            coefficient = round((q.x-p.x)*3)/3
            assert abs(q.x-p.x-coefficient) < 1e-14 and q.y == p.y
            values.append("{%r, %r, %r}" % (p.x, p.y, coefficient))
        stream.write("\t{" + ", ".join(values) + "},\n")
    stream.write("}\n")
