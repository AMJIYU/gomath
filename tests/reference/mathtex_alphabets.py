#!/usr/bin/env python3
"""Development only: pinned mathematical alphabet outlines and FreeType masks.

Reads original STIXGeneral with fontTools/FreeType, never gomath. The generated
Go derivative is named Gomath Math Alphabets under SIL OFL 1.1. Go tests need
only committed metrics/PNG references, not Python, source fonts or FreeType.
"""
import argparse
import hashlib
import json
from pathlib import Path
import string
import unicodedata

import fontTools
import freetype
from fontTools import subset
from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont
from PIL import Image, __version__ as pillow_version

from mathtex_symbols import outline

SOURCE_HASH = "5add3f3f2bd7fd897d2fa5ccbe468607c52111dc44cdfaaf2d851a574f5357a7"
LETTERS = string.ascii_uppercase + string.ascii_lowercase
EXCEPTIONS = {
    "mathbb": dict(zip("CHNPQRZ", "ℂℍℕℙℚℝℤ")),
    "mathcal": dict(zip("BEFHILRMego", "ℬℰℱℋℐℒℛℳℯℊℴ")),
    "mathfrak": dict(zip("CHIRZ", "ℭℌℑℜℨ")),
}
FAMILIES = {"mathbb": "DOUBLE-STRUCK", "mathcal": "SCRIPT", "mathfrak": "FRAKTUR"}


def mapped(command, char):
    if char in EXCEPTIONS[command]:
        return EXCEPTIONS[command][char]
    suffix = ("DIGIT " + ["ZERO", "ONE", "TWO", "THREE", "FOUR", "FIVE", "SIX", "SEVEN", "EIGHT", "NINE"][int(char)]
              if char.isdigit() else ("CAPITAL " if char.isupper() else "SMALL ") + char.upper())
    return unicodedata.lookup("MATHEMATICAL " + FAMILIES[command] + " " + suffix)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--font", type=Path, required=True)
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    args = ap.parse_args()
    digest = hashlib.sha256(args.font.read_bytes()).hexdigest()
    if digest != SOURCE_HASH:
        raise ValueError("source STIXGeneral hash differs from reviewed font")
    f = TTFont(args.font)
    if f["head"].unitsPerEm != 1000:
        raise ValueError("unexpected units per em")
    meta = {"file": args.font.name, "sha256": digest, "units_per_em": 1000,
            "versions": sorted({n.toUnicode() for n in f["name"].names if n.nameID == 5})}
    lines = ["// Code generated by tests/reference/mathtex_alphabets.py; DO NOT EDIT.",
             "// Gomath Math Alphabets: original STIXGeneral outlines, SIL OFL 1.1.",
             "// See LICENSE-STIX.txt; no STIX reserved primary name is used.",
             "// STIXGeneral.otf SHA256 " + digest, "package mathtex", "",
             "var mathAlphabetRunes = [...][]rune{", 'nil,']
    records = []
    for command in FAMILIES:
        chars = LETTERS + (string.digits if command == "mathbb" else "")
        runes = "".join(mapped(command, char) for char in chars)
        lines.append('[]rune("' + runes + '"), // ' + command)
        for char, rune in zip(chars, runes):
            glyph, advance, ops = outline(f, rune)
            gs = f.getGlyphSet()
            bounds = BoundsPen(gs)
            gs[glyph].draw(bounds)
            records.append({"command": command, "input": char, "rune": rune,
                            "glyph": glyph, "advance_em": advance / 1000,
                            "bbox_em": [v / 1000 for v in bounds.bounds],
                            "raster": f"{command}-{ord(char):04x}.png", "font": meta,
                            "operations": ops, "advance": advance})
    lines += ["}", "", "var mathAlphabetOutlines = map[rune]setOutline{"]
    for record in records:
        lines.append(f"{record['rune']!r}: {{advance: {record['advance']}, operations: []setOperation{{")
        for op, xy in record["operations"]:
            values = ", ".join(f"{v:g}" for v in xy)
            lines.append(f"{{kind: '{op}', xy: [6]float64{{{values}}}}},")
        lines.append("}},")
    lines.append("}")
    (args.root / "mathtex" / "math_alphabets_data.go").write_text("\n".join(lines) + "\n")
    data_dir = args.root / "tests" / "data" / "mathtex" / "alphabets"
    data_dir.mkdir(parents=True, exist_ok=True)
    face = freetype.Face(str(args.font))
    face.set_pixel_sizes(0, 256)
    load_flags = freetype.FT_LOAD_RENDER | freetype.FT_LOAD_NO_HINTING | freetype.FT_LOAD_NO_BITMAP
    for record in records:
        image = Image.new("L", (384, 384))
        face.load_char(record["rune"], load_flags)
        slot = face.glyph
        bitmap = slot.bitmap
        if bitmap.pixel_mode != freetype.FT_PIXEL_MODE_GRAY or bitmap.pitch < bitmap.width:
            raise ValueError("unexpected FreeType bitmap format")
        mask = Image.frombytes("L", (bitmap.width, bitmap.rows), bytes(bitmap.buffer), "raw", "L", bitmap.pitch)
        origin = (48 + slot.bitmap_left, 288 - slot.bitmap_top)
        if origin[0] < 0 or origin[1] < 0 or origin[0] + mask.width > 384 or origin[1] + mask.height > 384:
            raise ValueError("reference canvas clips source glyph")
        image.paste(mask, origin)
        image.save(data_dir / record["raster"])
        del record["operations"], record["advance"]
    # Tiny genuine custom-font fixture exercises successful strict Unicode
    # loading as well as missing-glyph rejection, without system-font test I/O.
    custom = TTFont(args.font, recalcTimestamp=False)
    options = subset.Options()
    options.drop_tables += ["FFTM"]
    options.recalc_timestamp = False
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=[ord(r) for r in "ℝ𝒜𝔄"])
    sub.subset(custom)
    names = {1: "Gomath Alphabet Test", 2: "Regular", 3: "GomathAlphabetTest-Regular",
             4: "Gomath Alphabet Test Regular", 6: "GomathAlphabetTest-Regular"}
    for record in custom["name"].names:
        if record.nameID in names:
            record.string = names[record.nameID].encode(record.getEncoding())
    cff = custom["CFF "].cff
    cff.fontNames = ["GomathAlphabetTest-Regular"]
    cff.topDictIndex[0].FamilyName = "Gomath Alphabet Test"
    cff.topDictIndex[0].FullName = "Gomath Alphabet Test Regular"
    custom_path = data_dir / "GomathAlphabetTest.otf"
    custom.save(custom_path)
    manifest = {"provenance": "Original font cmap/hmtx/CFF BoundsPen; unhinted raster via FreeType, never gomath.",
                "fonttools": fontTools.__version__, "pillow": pillow_version,
                "freetype": ".".join(map(str, freetype.version())), "unicode": unicodedata.unidata_version,
                "load_flags": "FT_LOAD_RENDER | FT_LOAD_NO_HINTING | FT_LOAD_NO_BITMAP",
                "raster": {"width": 384, "height": 384, "ppem": 256, "origin_x": 48, "baseline_y": 288},
                "custom_font": {"file": custom_path.name, "runes": "ℝ𝒜𝔄",
                                "sha256": hashlib.sha256(custom_path.read_bytes()).hexdigest(),
                                "license": "SIL OFL 1.1; mathtex/LICENSE-STIX.txt"},
                "records": records}
    (data_dir / "reference.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")


if __name__ == "__main__":
    main()
