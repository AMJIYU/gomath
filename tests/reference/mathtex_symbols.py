#!/usr/bin/env python3
"""Development only: extract pinned font outlines and independent references.

No gomath code is loaded. fontTools reads source OTF/TTF files; BoundsPen and
Pillow/FreeType independently produce metrics and raster oracles. Normal Go
tests consume committed JSON/PNG files and require none of these tools/fonts.
"""
import argparse
import hashlib
import json
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.recordingPen import RecordingPen
from fontTools.ttLib import TTFont
import fontTools
from PIL import Image, ImageDraw, ImageFont, __version__ as pillow_version

SYMBOLS = {
    "in": "∈", "notin": "∉", "ni": "∋", "subset": "⊂", "supset": "⊃",
    "subseteq": "⊆", "supseteq": "⊇", "cup": "∪", "cap": "∩", "emptyset": "∅",
    "setminus": "∖", "subsetneq": "⊊", "supsetneq": "⊋",
    "nsubseteq": "⊈", "nsupseteq": "⊉",
}
ALIASES = {"owns": "ni"}
STYLES = ["regular", "bold", "italic", "bold-italic"]
GO_FILES = ["Go-Regular.ttf", "Go-Bold.ttf", "Go-Italic.ttf", "Go-Bold-Italic.ttf"]


def load_font(filename):
    f = TTFont(filename)
    versions = sorted({n.toUnicode() for n in f["name"].names if n.nameID == 5})
    return f, {"file": filename.name, "sha256": hashlib.sha256(filename.read_bytes()).hexdigest(),
               "versions": versions, "units_per_em": f["head"].unitsPerEm}


def outline(f, rune):
    name = f.getBestCmap().get(ord(rune))
    if not name:
        raise ValueError(f"missing source glyph {rune}")
    gs = f.getGlyphSet()
    pen = RecordingPen()
    gs[name].draw(pen)
    operations = []
    for op, args in pen.value:
        if op == "moveTo":
            operations.append(("M", args[0]))
        elif op == "lineTo":
            operations.extend(("L", point) for point in args)
        elif op == "curveTo" and len(args) == 3:
            operations.append(("C", tuple(v for point in args for v in point)))
        elif op == "closePath":
            operations.append(("Z", ()))
        else:
            raise ValueError(f"unsupported extraction operation {op}: {args}")
    return name, f["hmtx"].metrics[name][0], operations


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--font-dir", type=Path, required=True, help="original STIXGeneral OTF directory")
    ap.add_argument("--gofont-dir", type=Path, required=True, help="golang.org/x/image/font/gofont directory")
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    ap.add_argument("--outlines-only", action="store_true", help="do not regenerate reference JSON/PNGs")
    args = ap.parse_args()
    stix = [load_font(args.font_dir / n) for n in ("STIXGeneral.otf", "STIXGeneralBol.otf")]
    lines = ["// Code generated by tests/reference/mathtex_symbols.py; DO NOT EDIT.",
             "// Gomath Set Symbols: selected original STIX font outlines, SIL OFL 1.1.",
             "// See LICENSE-STIX.txt. This derivative has no STIX reserved primary font name."]
    for _, meta in stix:
        lines.append("// " + meta["file"] + " SHA256 " + meta["sha256"])
    lines += ["package mathtex", "", "var supplementalSetOutlines = map[rune][2]setOutline{"]
    for command, rune in SYMBOLS.items():
        if command in ("cup", "cap"):
            continue
        lines.append(f"{rune!r}: {{")
        for f, _ in stix:
            _, advance, ops = outline(f, rune)
            if f["head"].unitsPerEm != 1000:
                raise ValueError("production outline units changed")
            lines.append(f"{{advance: {advance}, operations: []setOperation{{")
            for op, xy in ops:
                values = ", ".join(format(v, ".15g") for v in xy)
                lines.append("{kind: '"+op+"', xy: [6]float64{"+values+"}},")
            lines.append("}},")
        lines.append("},")
    lines.append("}")
    (args.root / "mathtex/set_symbols_data.go").write_text("\n".join(lines)+"\n")
    if args.outlines_only:
        return
    native = [load_font(args.gofont_dir / "ttfs" / n) for n in GO_FILES]
    data_dir = args.root / "tests/data/mathtex/set-symbols"
    data_dir.mkdir(parents=True, exist_ok=True)
    records = []
    for command, rune in SYMBOLS.items():
        for style, style_name in enumerate(STYLES):
            # Relations are upright in the supplemental mathematical face;
            # bold is an actual source font. Native cup/cap keep Go variants.
            is_native = command in ("cup", "cap")
            f, meta = native[style] if is_native else stix[style & 1]
            glyph = f.getBestCmap()[ord(rune)]
            gs = f.getGlyphSet()
            bounds = BoundsPen(gs)
            gs[glyph].draw(bounds)
            units = f["head"].unitsPerEm
            advance = f["hmtx"].metrics[glyph][0] / units
            bbox = [v / units for v in bounds.bounds]
            font_path = args.gofont_dir / "ttfs" / GO_FILES[style] if is_native else args.font_dir / meta["file"]
            image = Image.new("L", (320, 320))
            font = ImageFont.truetype(str(font_path), 256)
            ImageDraw.Draw(image).text((32, 224), rune, font=font, fill=255, anchor="ls", stroke_width=0)
            png_name = f"{command}-{style_name}.png"
            image.save(data_dir / png_name)
            records.append({"command": command, "rune": rune, "style": style, "font": meta,
                            "glyph": glyph, "native": is_native, "advance_em": advance,
                            "bbox_em": bbox, "raster": png_name,
                            # sfnt/text retains raw glyf coordinates; FreeType and
                            # fontTools GlyphSet apply hmtx.lsb - glyf.xMin. Keep
                            # this independent source-font origin offset explicit.
                            "outline_origin_x_em": ((f["glyf"][glyph].xMin - f["hmtx"].metrics[glyph][1]) / units
                                                    if is_native else 0)})
    manifest = {"provenance": "Source-font cmap/hmtx/outlines via fontTools BoundsPen; raster via Pillow/FreeType, never gomath.",
                "fonttools": fontTools.__version__, "pillow": pillow_version,
                "freetype": ImageFont.core.freetype2_version,
                "raster": {"width": 320, "height": 320, "ppem": 256, "origin_x": 32, "baseline_y": 224},
                "aliases": ALIASES, "records": records}
    (data_dir / "reference.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+"\n")


if __name__ == "__main__":
    main()
